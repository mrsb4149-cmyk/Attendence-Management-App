package com.example.attendancemanagementsystemapp;

public class Person {
    int id;
    String name;
    String mobile;
    String status;

    public Person(
            int id,
            String name,
            String mobile,
            String status) {

        this.id = id;
        this.name = name;
        this.mobile = mobile;
        this.status = status;
    }
}
